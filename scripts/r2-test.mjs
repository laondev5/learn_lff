// Offline security/contract checks. No R2 network calls and no DB access.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createHmac } from "node:crypto";
import { Module } from "node:module";
import path from "node:path";
import ts from "typescript";
process.env.R2_ACCOUNT_ID = "a".repeat(32);
process.env.R2_BUCKET_NAME = "test-videos";
process.env.R2_ACCESS_KEY_ID = "offline-test";
process.env.R2_SECRET_ACCESS_KEY = "offline-test";
process.env.AUTH_SECRET = "offline-test-token-secret";
const source = readFileSync("src/lib/r2.ts", "utf8").replace('import "server-only"', "");
const filename = path.resolve("src/lib/r2.offline.cjs");
const compiled = new Module(filename);
compiled.filename = filename;
compiled.paths = Module._nodeModulePaths(path.dirname(filename));
compiled._compile(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { parseR2Url, r2VideoUrl, getR2PlaybackUrl, validateUploadToken, signR2Part } = compiled.exports;
const key = "teachers/teacher1/videos/unique-key";
const url = r2VideoUrl(key);
assert.equal(parseR2Url(url), key);
for (const invalid of [null, "", url + "?signature=x", url + "#hash", url.replace("https:", "http:"), url.replace("test-videos", "other-bucket"), url.replace("a".repeat(32), "b".repeat(32)), url.replace("/teachers/", "/%74eachers/"), url.replace("/teachers/", "/../teachers/"), url.replace("https://", "https://user@"), url + "/%2e%2e/secret", url + "/%5Csecret"]) assert.equal(parseR2Url(invalid), null);
const data = { teacher: "teacher1", key, uploadId: "offline-upload", size: 1024, expires: Date.now() + 60000 };
function tokenFor(data) { const payload = Buffer.from(JSON.stringify(data)).toString("base64url"); return payload + "." + createHmac("sha256", process.env.AUTH_SECRET).update("r2-upload-v1:" + payload).digest("base64url"); }
const token = tokenFor(data);
assert.deepEqual(validateUploadToken(token, "teacher1"), data);
assert.throws(() => validateUploadToken(token, "teacher2"));
assert.throws(() => validateUploadToken(token + "x", "teacher1"));
assert.throws(() => validateUploadToken(tokenFor({ ...data, expires: 1 }), "teacher1"));
assert.throws(() => validateUploadToken(tokenFor({ ...data, key: "teachers/other/videos/key" }), "teacher1"));
assert.throws(() => validateUploadToken(tokenFor({ ...data, size: -1 }), "teacher1"));
await assert.rejects(signR2Part(data, 2));
await assert.rejects(signR2Part(data, 0));
await assert.rejects(getR2PlaybackUrl(url, 0));
const signed = new URL(await getR2PlaybackUrl(url, 7));
assert.equal(signed.searchParams.get("X-Amz-Expires"), "7");
assert.equal(signed.pathname, new URL(url).pathname);
assert.equal(parseR2Url(signed.href), null);
console.log("PASS: canonical bucket parsing, token ownership/tampering/expiry, part bounds, and deadline-capped signing (offline).");
